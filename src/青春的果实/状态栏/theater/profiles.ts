
/**
 * 内置角色阶段人设
 *
 * 从世界书 EJS 条目中提取各阶段的纯文本人设。
 * 运行时根据 MVU 变量中的关系状态 + 好感度自动选择对应阶段。
 */

/** 阶段人设条目 */
interface StageProfile {
  /** 调色盘 + 衍生画面 */
  personality: string;
  /** 二次解释（写法指导） */
  interpretation: string;
}

/** 角色阶段映射 */
type StageKey = string; // 关系状态值，如 '初识'、'恋人'、'决裂'

/**
 * 根据角色名、关系状态、好感度，返回对应阶段的内置人设
 */
export function getStageProfile(
  characterName: string,
  relation: string,
  favor: number,
): StageProfile | null {
  const profiles = PROFILES[characterName];
  if (!profiles) return null;

  // 按优先级匹配阶段
  // 1. 先看关系状态是否有直接匹配（决裂/封心/疏远/恋人）
  if (profiles[relation]) return profiles[relation];

  // 2. 按好感度区间匹配
  if (favor >= 60 && profiles['暧昧']) return profiles['暧昧'];
  if (favor >= 30 && profiles['熟悉']) return profiles['熟悉'];

  // 3. 默认阶段
  return profiles['默认'] ?? null;
}

