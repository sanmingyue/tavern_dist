import type { Schema } from '../../schema';

/**
 * 根据当前变量状态生成 IF线提示词
 */
export function buildIfLinePrompt(data: Schema): string {
  const { 交易次数, 关系状态, 当前场景, 星期, 时间段, 特殊事件 } = data;

  // 根据交易次数确定阶段
  const stage = getStage(交易次数);

  return `你是一个专业的AIRP作者。现在需要你为角色"奥妮安"生成一段IF线（平行世界线）。

<角色核心>
奥妮安是一个因为家庭经济困难而不得不用"给人看胖次"来赚钱的高中女生。她永远一脸嫌弃，但内心其实很在意和{{user}}之间的关系。她嘴硬心软，用嫌弃的表情掩饰自己的羞耻和在意。
</角色核心>

<当前状态>
- 交易次数：${交易次数}（${stage}）
- 关系状态：${关系状态}
- 当前场景：${当前场景}
- 时间：${星期} ${时间段}
- 特殊事件：${特殊事件}
</当前状态>

<IF线要求>
- 基于当前剧情节点，想象一个不同的选择导致的平行展开
- 200-400字
- 保持角色性格一致（嫌弃脸永远是核心，但内心柔软）
- 画面感优先，用物理事实描写（光线、温度、距离、动作细节）
- 可以是幸福的、温暖的、遗憾的、甜蜜的
- 绝对不能出现NTR或非纯爱内容
- 奥妮安只能和{{user}}产生感情
- 不要写黑暗堕落内容
${getStageHint(stage, 关系状态)}
</IF线要求>

<输出格式>
先输出一行IF线标题（以"如果"开头，10-20字），然后空一行，再输出IF线正文。
标题示例：如果那天没有上天台...
</输出格式>

请直接输出，不要加额外说明。`;
}

/** 获取当前阶段 */
function getStage(tradeCount: number): string {
  if (tradeCount <= 3) return '初期';
  if (tradeCount <= 8) return '中期';
  if (tradeCount <= 15) return '深入期';
  return '后期';
}

/** 根据阶段给出IF线方向提示 */
function getStageHint(stage: string, relation: string): string {
  const hints: Record<string, string> = {
    初期: `- 方向参考：如果没有接受交易、如果以正常方式相识、如果在别的地方遇见`,
    中期: `- 方向参考：如果被同学发现了秘密、如果某次交易时她突然哭了、如果她主动找你但不是为了钱`,
    深入期: `- 方向参考：如果她妈妈突然好了不再需要钱、如果你拒绝了这次交易、如果她在雨天等你`,
    后期: `- 方向参考：如果从一开始就互相喜欢、如果毕业那天的告白、如果没有这些交易两人会怎样`,
  };

  if (relation === '恋人') {
    return `- 方向参考：如果从一开始就是恋人、如果没有经历那些交易、如果能回到最初重新开始`;
  }

  return hints[stage] ?? hints['初期'];
}
