let count = 0;

for (const [district, street, buildings] of data) {
  const streetDir = path.join(BASE, district, street);

  for (const [name, type, sizi, extra] of buildings) {
    const fileName = name.replace(/[·\s/\\:*?"<>|]/g, '_') + '.yaml';
    const filePath = path.join(streetDir, fileName);

    // 解析四至
    const siziParts = sizi.split(' ').filter(s => s.includes(':'));
    let siziYaml = '';
    if (siziParts.length > 0) {
      siziYaml = '  四至:\n';
      for (const part of siziParts) {
        const [dir, ...desc] = part.split(':');
        siziYaml += `    ${dir}: ${desc.join(':')}\n`;
      }
    }

    let content = `<${name}>\n${name}:\n  位置: ${district}·${street}·${sizi.split(' ')[0].split(':')[1] || ''}\n  类型: ${type}\n`;
    if (siziYaml) content += siziYaml;
    if (extra) content += `  详情: ${extra}\n`;
    content += `</${name}>\n`;

    // 确保目录存在
    fs.mkdirSync(streetDir, { recursive: true });
    fs.writeFileSync(filePath, content, 'utf-8');
    count++;
  }
}

console.log(`总共生成了 ${count} 个第四层建筑文件`);
