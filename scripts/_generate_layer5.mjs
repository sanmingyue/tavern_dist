// 商铺→店铺列表+老板信息，游乐场→项目价格，公寓→户型房租
import fs from 'fs';
import path from 'path';

const BASE = 'src/角色卡/XX市/世界书/地图';
let count = 0;

function writeL5(district, street, buildingName, dirName, files) {
  const l5Dir = path.join(BASE, district, street, dirName);
  fs.mkdirSync(l5Dir, { recursive: true });
  for (const [fname, content] of files) {
    const fp = path.join(l5Dir, fname);
    if (!fs.existsSync(fp)) {
      fs.writeFileSync(fp, content, 'utf-8');
      count++;
    }
  }
}

