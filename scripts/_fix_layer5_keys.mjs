// 解析每个顺序5的条目，从其文件路径提取街道名，替换主关键字
let modCount = 0;

// 匹配顺序5条目的完整块: 从 "- 名称:" 到下一个 "- 名称:" 或文件结尾
// 我们用正则逐条目处理
const entryRegex = /^( +- 名称: .+\n(?:(?! +- 名称:).+\n)*)/gm;

content = content.replace(entryRegex, (block) => {
  // 检查是否是顺序5
  const orderMatch = block.match(/顺序: 5/);
  if (!orderMatch) return block;

  // 提取文件路径
  const fileMatch = block.match(/文件: 世界书\/地图\/([^/]+)\/([^/]+)\//);
  if (!fileMatch) return block;

  const streetName = fileMatch[2]; // 街道名
  const aliases = streetAliases[streetName];
  if (!aliases) return block; // 未找到映射，保留原样

  // 替换主关键字块
  const newKeys = aliases.map(k => `            - ${k}`).join('\n');
  const newBlock = block.replace(
    /关键字:\n((?:            - .+\n)*?)          次要关键字:/,
    `关键字:\n${newKeys}\n          次要关键字:`
  );

  if (newBlock !== block) modCount++;
  return newBlock;
});

fs.writeFileSync(filePath, content);
console.log(`修改了 ${modCount} 个第5层条目的主关键字`);

