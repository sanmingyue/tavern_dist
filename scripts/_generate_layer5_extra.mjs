import fs from 'fs';
import path from 'path';

const BASE = 'src/角色卡/XX市/世界书/地图';
let count = 0;

function writeL5(district, street, parentDir, subDirOrFiles, maybeFiles) {
  const files = maybeFiles || subDirOrFiles;
  const l5Dir = maybeFiles
    ? path.join(BASE, district, street, parentDir, subDirOrFiles)
    : path.join(BASE, district, street, parentDir);
  fs.mkdirSync(l5Dir, { recursive: true });
  for (const [fname, content] of files) {
    const fp = path.join(l5Dir, fname);
    if (!fs.existsSync(fp)) {
      fs.writeFileSync(fp, content, 'utf-8');
      count++;
    }
  }
}

