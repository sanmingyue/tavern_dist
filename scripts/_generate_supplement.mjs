import fs from 'fs';
import path from 'path';

const BASE = 'src/角色卡/XX市/世界书/地图';

function writeBuilding(district, street, name, content) {
  const streetDir = path.join(BASE, district, street);
  const fileName = name.replace(/[·\s/\\:*?"<>|]/g, '_') + '.yaml';
  const filePath = path.join(streetDir, fileName);
  if (fs.existsSync(filePath)) return false;
  fs.mkdirSync(streetDir, { recursive: true });
  fs.writeFileSync(filePath, content, 'utf-8');
  return true;
}

let count = 0;

function add(district, street, name, yaml) {
  if (writeBuilding(district, street, name, yaml)) count++;
}

